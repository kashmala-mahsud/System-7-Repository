No1 = int(input("Enter a number: "))
No2 = int(input("Enter another number: "))

print(f"Addition: {No1 + No2}")
print(f"Subtraction: {No1 - No2}")
print(f"Multiplication: {No1 * No2}")
print(f"Division: {No1 / No2}")
print(f"Modulus: {No1 % No2}")
print(f"Exponentiation: {No1 ** No2}")
print(f"Floor Division: {No1 // No2}")
print(f"Square Root of {No1}: {No1 ** 0.5}")
print(f"Square Root of {No2}: {No2 ** 0.5}")
print(f"Absolute Value of {No1}: {abs(No1)}")
print(f"Absolute Value of {No2}: {abs(No2)}")
print(f"Power of {No1} raised to {No2}: {pow(No1, No2)}")
print(f"Maximum of {No1} and {No2}: {max(No1, No2)}")
print(f"Minimum of {No1} and {No2}: {min(No1, No2)}")
print(f"Round of {No1}: {round(No1)}")
print(f"Round of {No2}: {round(No2)}")
print(f"Ceiling of {No1}: {int(-(-No1 // 1))}")
print(f"Ceiling of {No2}: {int(-(-No2 // 1))}")
